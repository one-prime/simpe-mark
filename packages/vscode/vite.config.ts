import { defineConfig } from 'vite';
import { fontAlias } from '../../scripts/mathjax-font.mjs';
import { noticesPlugin } from '../../scripts/third-party.mjs';

// The webview bundle: dist/webview/webview.js plus chunks it imports on demand (MathJax and its
// font parts). Relative chunk URLs resolve against webview.js, which is a webview resource URI.
export default defineConfig({
  base: './',
  // MathJax's default font stays out: the math is drawn with ours (see scripts/mathjax-font.mjs).
  resolve: { alias: [fontAlias] },
  // Everything the bundle includes from other projects, with its license (packaged in the .vsix).
  plugins: [
    noticesPlugin({
      file: new URL('THIRD_PARTY_NOTICES.txt', import.meta.url).pathname,
      title: 'SimpleMark for VS Code: third-party notices',
      intro:
        'SimpleMark is MIT-licensed (see LICENSE). It includes the software below, each under its own\nlicense, and values copied from the projects listed under design references.\nGenerated by the build from the bundle (scripts/third-party.mjs); do not edit.',
    }),
  ],
  build: {
    outDir: 'dist/webview',
    emptyOutDir: true,
    target: 'es2022',
    // The preload helper adds <link> tags at run time; not needed in a webview.
    modulePreload: false,
    // MathJax and its font parts are large but load only when a document has math.
    chunkSizeWarningLimit: 2000,
    rolldownOptions: {
      input: 'src/webview/main.ts',
      output: {
        format: 'es',
        entryFileNames: 'webview.js',
        chunkFileNames: 'chunks/[name]-[hash].js',
      },
    },
  },
});
