// Writes src/languages.ts: every highlight.js language with its aliases, the languages it
// embeds (HTML's <script> and <style>), and a static import, so bundlers make each language a
// chunk that loads only when a document has a code block in it. Run after updating highlight.js:
//   node packages/highlight/scripts/languages.mjs

import { readdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const hljs = require('highlight.js/lib/core');
const { version } = require('highlight.js/package.json');
const dir = new URL('../../../node_modules/highlight.js/lib/languages/', import.meta.url);
const names = readdirSync(dir)
  .filter((file) => file.endsWith('.js') && !file.endsWith('.js.js'))
  .map((file) => file.slice(0, -3))
  .sort();

/** Languages a definition embeds through `subLanguage`, anywhere in its (cyclic) modes. */
function embedded(definition) {
  const found = new Set();
  const seen = new Set();
  const visit = (value) => {
    if (!value || typeof value !== 'object' || seen.has(value)) return;
    seen.add(value);
    if (Array.isArray(value)) return value.forEach(visit);
    for (const sub of [value.subLanguage].flat()) if (typeof sub === 'string') found.add(sub);
    Object.values(value).forEach(visit);
  };
  visit(definition);
  return [...found].sort();
}

const list = (items) => `[${items.map((item) => `'${item}'`).join(', ')}]`;
const lines = names.map((name) => {
  const definition = require(`highlight.js/lib/languages/${name}`)(hljs);
  const aliases = [definition.aliases ?? []].flat().map((a) => a.toLowerCase()).filter((a) => a !== name);
  const uses = embedded(definition).filter((n) => n !== name && names.includes(n));
  const fields = [
    aliases.length ? `aliases: ${list(aliases)}` : '',
    uses.length ? `uses: ${list(uses)}` : '',
    `load: () => import('highlight.js/lib/languages/${name}')`,
  ].filter(Boolean);
  const key = /^[a-z_][a-z0-9_]*$/.test(name) ? name : `'${name}'`;
  return `  ${key}: { ${fields.join(', ')} },`;
});

const source = `// The languages of highlight.js ${version} (${names.length}), with their aliases and the languages they embed.
// Each is a static import so any bundler makes it a separate chunk. Generated by
// scripts/languages.mjs; run it again after updating highlight.js.

import type { LanguageFn } from 'highlight.js';

export interface LanguageEntry {
  aliases?: string[];
  /** Languages it highlights parts of (HTML: CSS and JavaScript). */
  uses?: string[];
  load: () => Promise<{ default: LanguageFn }>;
}

export const LANGUAGES: Record<string, LanguageEntry> = {
${lines.join('\n')}
};
`;
writeFileSync(new URL('../src/languages.ts', import.meta.url), source);
console.log(`${names.length} languages written`);
